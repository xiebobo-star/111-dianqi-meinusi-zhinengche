// *************************** 例程说明 ***************************
// 上电即在 P33.9 和 P21.6 两路同时输出舵机标准信号：
//   脉宽 1500us  周期 20ms（即 50Hz）
// 两路完全一样，不需要按键、串口或任何外部操作，烧录后复位即生效
// 如果发现现象与说明严重不符 请参照本文件最下方 例程常见问题说明 进行排查

// **************************** 代码区域 ****************************
#define PWM_FREQ                (50)                                    // PWM 频率 50Hz  ->  周期 20ms
#define PWM_PERIOD_US           (1000000 / PWM_FREQ)                    // 周期换算成 us，即 20000us
#define SERVO_PULSE_US          (1500)                                  // 目标脉宽 1500us

// 占空比按库的量纲换算：PWM_DUTY_MAX(10000) 对应一个完整周期
// 1500us / 20000us * 10000 = 750
#define SERVO_DUTY              ((uint32)((uint64)SERVO_PULSE_US * PWM_DUTY_MAX / PWM_PERIOD_US))

#define PWM_CH1                 (ATOM1_CH1_P33_9)                       // 第 1 路：P33.9
#define PWM_CH2                 (ATOM1_CH4_P21_6)                       // 第 2 路：P21.6

int core0_main(void)
{
    clock_init();                   // 获取时钟频率<务必保留>
    debug_init();                   // 初始化默认调试串口
    // 此处编写用户代码 例如外设初始化代码等

    pwm_init(PWM_CH1, PWM_FREQ, SERVO_DUTY);        // P33.9 上电即输出 脉宽1500us 周期20ms
    pwm_init(PWM_CH2, PWM_FREQ, SERVO_DUTY);        // P21.6 上电即输出 脉宽1500us 周期20ms

    // 此处编写用户代码 例如外设初始化代码等
    cpu_wait_event_ready();         // 等待所有核心初始化完毕
    while (TRUE)
    {
        // 此处编写需要循环执行的代码
        // 两路信号的频率和脉宽在 pwm_init 时已经定下来了，这里不需要再改动
        // 需要改脉宽时调用（duty = 脉宽us / 2，例如 1500us -> 750）：
        //     pwm_set_duty(PWM_CH1, 750);
        //     pwm_set_duty(PWM_CH2, 750);

        // 此处编写需要循环执行的代码
    }
}

