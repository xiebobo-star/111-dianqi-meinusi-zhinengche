/*********************************************************************************************************************
* 文件名            menu_ui.h
* 说明              TC264 多级菜单界面（屏幕显示 + 按键响应 + 参数修改 + 弹窗确认 + 状态页）
* 用法              cpu0_main 里两行：
*                     menu_ui_init();        // 初始化屏幕/按键/参数/Flash，并画出主菜单
*                     menu_ui_run();         // 菜单主循环（进去就不返回了）
* 按键              按键1 = 上选   按键2 = 下选   按键3 = 确定   按键4 = 返回
*                   参数改完按 3/4 键退出就自动保存（不用另按保存）  长按按键4 = 直接回主菜单
********************************************************************************************************************/
#ifndef _menu_ui_h_
#define _menu_ui_h_

#include "zf_common_headfile.h"

void menu_ui_init      (void);      // 初始化（屏幕、按键、参数、Flash 载入），并画出主菜单
void menu_ui_run       (void);      // 菜单主循环（自己刷屏，不会返回）
void menu_ui_tick_10ms (void);      // 10ms 定时中断里调用（给提示框计时用）

#endif
