/*********************************************************************************************************************
* 文件名            cpu1_main.c
* 说明              TC264 是双核，CPU1 的入口在这里。本工程菜单跑在 CPU0，CPU1 不用干活，
*                   只做最基本的初始化就等着（屏幕 / 按键 / Flash 都在 CPU0 里，别在这里重复初始化）
* 本文件基于逐飞 TC264 开源库的空工程模板修改
********************************************************************************************************************/
#include "zf_common_headfile.h"
#pragma section all "cpu1_dsram"
// 将本语句与#pragma section all restore语句之间的全局变量都放在CPU1的RAM中

// **************************** 代码区域 ****************************
void core1_main(void)
{
    disable_Watchdog();                     // 关闭看门狗
    interrupt_global_enable(0);             // 打开全局中断
    // 此处编写用户代码 例如外设初始化代码等
    // 本工程 CPU1 没有任务；菜单、屏幕、按键、Flash 全部在 CPU0
    // 注意：屏幕初始化只能在一个核里做（CPU0 已经做了 menu_display_init()），这里不要重复调用

    cpu_wait_event_ready();                 // 等待所有核心初始化完毕（CPU0 走完初始化才会继续往下跑）

    while (TRUE)
    {
        // 此处编写需要循环执行的代码
    }
}
#pragma section all restore
