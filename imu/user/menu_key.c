/*********************************************************************************************************************
* 文件名            menu_key.c
* 说明              按键封装实现。真正干活的是库里的 key_init / key_scanner / key_get_state
*                   库里 key_press_time 记的是「扫描周期数」，所以 menu_key_scan() 必须严格按 menu_key_init() 给的周期被调用
*                   —— 本工程由 CCU60_CH0 的 10ms 定时中断保证（见 user/isr.c）
********************************************************************************************************************/
#include "menu_config.h"
#include "menu_key.h"

static uint32 menu_key_cnt = 0;                                     // 累计按键次数

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按键初始化
// 参数说明     period_ms       扫描周期 ms，必须和调用 menu_key_scan() 的定时中断周期一致
//-------------------------------------------------------------------------------------------------------------------
void menu_key_init (uint32 period_ms)
{
    key_init(period_ms);
    menu_key_clear_all();
    menu_key_cnt = 0;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按键扫描（定时中断里调用）
//-------------------------------------------------------------------------------------------------------------------
void menu_key_scan (void)
{
    key_scanner();
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读按键状态（不清状态）
//-------------------------------------------------------------------------------------------------------------------
key_state_enum menu_key_state (uint8 key_index)
{
    zf_assert(KEY_NUMBER > key_index);
    return key_get_state((key_index_enum)key_index);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判断是否短按，并顺手把状态清掉
//-------------------------------------------------------------------------------------------------------------------
uint8 menu_key_short (uint8 key_index)
{
    if (KEY_SHORT_PRESS == menu_key_state(key_index))
    {
        key_clear_state((key_index_enum)key_index);
        menu_key_cnt ++;
        return 1;
    }
    return 0;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判断是否长按，并顺手把状态清掉
//-------------------------------------------------------------------------------------------------------------------
uint8 menu_key_long (uint8 key_index)
{
    if (KEY_LONG_PRESS == menu_key_state(key_index))
    {
        key_clear_state((key_index_enum)key_index);
        menu_key_cnt ++;
        return 1;
    }
    return 0;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     清除所有按键状态
//-------------------------------------------------------------------------------------------------------------------
void menu_key_clear_all (void)
{
    key_clear_all_state();
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     累计按键次数（运行状态页）
//-------------------------------------------------------------------------------------------------------------------
uint32 menu_key_press_cnt (void)
{
    return menu_key_cnt;
}
