/*********************************************************************************************************************
* 文件名            tof_config.h
* 说明              测距模块（VL53LXX 系列 TOF 激光测距）配置：型号、采样方式、量程、滤波、报警、显示
*                   改型号 / 改接线方式 / 改量程 / 改滤波，只改这里的宏，其它 .c 一行不用动
*
* 硬件接线（VL53LXX-V2 模块，丝印一般是 VL53L0X V2 / VL53LXX V2，6 个脚）：
*   模块脚      TC264 引脚    说明
*   --------    ----------    ------------------------------------------------------------------
*   VIN         5V            模块自带稳压，5V 最稳（3.3V 也能点，但激光电流大，5V 更保险）
*   GND         GND           共地
*   SCL         P33_4         软件 IIC 时钟（引脚在库文件 zf_device_dl1a.h 里，换线改那两行）
*   SDA         P33_5         软件 IIC 数据
*   XSHUT       P20_10        ★ 必须接：初始化时拉低再拉高，让模块重新上电复位
*                             不接的现象：第一次上电可能能测，MCU 一复位就报 DL1A self check error
*   GPIO1       不接          测距完成中断（真的想用中断再接到 P14_3，TOF_USE_INT = 1）
*
* 注意              引脚是逐飞库头文件里定的（库文件一行没改），本文件不重复定义引脚，
*                   避免同一个引脚两份定义打架；本文件只管「怎么测、怎么滤、怎么报警」
*                   如果你的模块插在主板的 IIC 座上，而那个座的脚不是 P33_4/P33_5，
*                   就改 libraries/zf_device/zf_device_dl1a.h 里 DL1A_SCL_PIN / DL1A_SDA_PIN 两行
********************************************************************************************************************/
#ifndef _tof_config_h_
#define _tof_config_h_

#include "zf_common_headfile.h"

// ============================================ 1. 传感器型号 ============================================
// VL53LXX-V2 这个模块市面上有两代芯片，寄存器完全不一样，所以默认「上电自动识别」：
//   读 0xC0   == 0xEE -> VL53L0X（量程 2 m）
//   读 0x010F == 0xEA -> VL53L1X（量程 4 m）
// 识别结果会打在串口上，测距统计页「型号」那一行也会显示实际认出来的芯片
#define TOF_SENSOR_AUTO             (0)         // 上电自动识别（VL53LXX-V2 用这个）
#define TOF_SENSOR_DL1A             (1)         // 强制按 VL53L0X 驱动
#define TOF_SENSOR_DL1B             (2)         // 强制按 VL53L1X 驱动
#define TOF_SENSOR_TYPE             (TOF_SENSOR_AUTO)

// ============================================ 2. 总开关 ============================================
#define TOF_MODULE_ENABLE           (1)         // 1 = 上电初始化测距模块（正常用这个）
                                                // 0 = 先不初始化：没接模块、只想调菜单/屏幕时用，
                                                //     这样不会去碰 IIC，也不会打印初始化失败的日志，
                                                //     测距页会显示「未初始化」

// ============================================ 3. 采样方式 ============================================
#define TOF_USE_INT                 (0)         // 0 = 不接 INT，10ms 定时中断里主动读寄存器（默认，4 根线就能跑）
                                                //     每 10ms 读一次 IIC 大约 0.1ms，占 CPU 百分之一左右，完全够用
                                                //     选它还有个原因：INT 默认那个脚 P14_3 在主板的「尽量不要使用」
                                                //     清单里（boot 相关），能不碰就不碰
                                                // 1 = 接 INT 线到 P14_3，模块测完一帧自动进中断读数，CPU 占用最低；
                                                //     如果接了之后出现「上电不进程序 / 复位异常」，说明这个板子
                                                //     确实不能占用 P14_3，改回 0、把 INT 线拔掉就行

// ============================================ 4. 量程与有效性 ============================================
// 超出下面的范围就认为「这一帧没有有效目标」，不参与滤波，也不会误报警
#define TOF_VALID_MIN_MM            (20)        // 小于 20 mm 当无效（TOF 贴太近本来就测不到）
#define TOF_RANGE_L0X_MM            (2000)      // VL53L0X 量程约 2 m
#define TOF_RANGE_L1X_MM            (4000)      // VL53L1X 量程约 4 m
#define TOF_VALID_MAX_MM            (TOF_RANGE_L0X_MM)
                                                // 只当「还没识别出型号时」的默认量程用；
                                                // 真正跑起来以后量程跟着识别结果走（见 tof_module_max_range_mm）
#define TOF_RAW_INVALID_MM          (8180)      // 库里「没读到」的原始值是 8190~8192，比这个大的一律当无效
#define TOF_TIMEOUT_MS              (250)       // 多少 ms 没有新数据就认为模块掉线（线掉了 / 没供电）
#define TOF_HOLD_MS                 (300)       // 连续无效超过这么久，显示值清 0（别一直挂着老数据骗人）
#define TOF_INIT_RETRY              (1)         // 初始化失败后再试几次（上电时序不稳时第一次容易失败）

// ============================================ 5. 滤波 ============================================
#define TOF_FILTER_WINDOW           (5)         // 中值滤波窗口长度，只能是 3 或 5（越大越稳，越跟手差）
#define TOF_EMA_SHIFT               (2)         // 平滑滤波：新值权重 1/(2^TOF_EMA_SHIFT)，2 = 1/4，3 = 1/8
#define TOF_FILTER_LEVEL_MAX        (2)         // 滤波等级上限：0 原始 / 1 中值 / 2 中值+平滑

// ============================================ 6. 报警 ============================================
#define TOF_DEFAULT_ALARM_MM        (300)       // 默认报警距离（mm）——没接菜单参数时用这个
#define TOF_ALARM_HYST_MM           (30)        // 回差：报警后要等距离大于「阈值 + 回差」才解除，防抖
#define TOF_ALARM_CONFIRM           (3)         // 连续几帧都小于阈值才真的报警（防一帧毛刺吓人）

// ============================================ 7. 曲线缓存 ============================================
#define TOF_HISTORY_NUM             (64)        // 实时测距页那条曲线存多少个采样点（老 -> 新）

// ============================================ 8. 参数来源 ============================================
// 1 = 报警距离 / 零点偏移 / 滤波等级 / 单位 / 报警开关 都用菜单参数（菜单里能改、断电保存）
// 0 = 用本文件里的默认值（把模块搬到别的工程、那个工程没有这套菜单时用）
#define TOF_USE_MENU_PARAM          (1)

// ============================================ 9. 串口日志 ============================================
// 1 = 初始化 / 重新初始化时往调试串口（UART0，115200）打一行结果，方便先确认模块通没通
// 注意：只在初始化的主程序里打印，中断里一句 printf 都没有（printf 太慢，绝不能进中断）
#define TOF_SERIAL_DEBUG            (1)

#endif
